export function climateProfileByCode(code) {
  return CLIMATE_PROFILES.find((profile) => profile.code.toLowerCase() === String(code).toLowerCase()) ?? null;
}

export function climateProfilesByGroup(group) {
  return CLIMATE_PROFILES.filter((profile) => profile.group === group);
}

export function climateHazardProfiles(hazard) {
  return CLIMATE_PROFILES.filter((profile) => profile.commonHazards.includes(hazard));
}

export function climatePlanningBrief(code) {
  const profile = climateProfileByCode(code);
  if (!profile) return null;
  return {
    code: profile.code,
    name: profile.name,
    summary: `${profile.temperaturePattern} ${profile.precipitationPattern}`,
    hazards: [...profile.commonHazards],
    actions: [...profile.planningNotes],
    temperatureRangeC: profile.typicalTemperatureC,
    precipitationRangeMm: profile.annualPrecipitationMm,
  };
}
