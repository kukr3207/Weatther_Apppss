export function alertRuleTemplate(templateId) {
  return ALERT_RULE_TEMPLATES.find((template) => template.id === templateId) ?? null;
}

export function alertRuleTemplatesByCategory(category) {
  return ALERT_RULE_TEMPLATES.filter((template) => template.category === category);
}

export function alertRuleCategories() {
  return [...new Set(ALERT_RULE_TEMPLATES.map((template) => template.category))].sort();
}

export function customizeAlertRule(templateId, changes = {}) {
  const template = alertRuleTemplate(templateId);
  if (!template) throw new TypeError(`Unknown alert template: ${templateId}.`);
  return {
    ...template,
    ...changes,
    id: changes.id ?? `${template.id}-custom`,
    conditions: changes.conditions ?? template.conditions.map((condition) => ({ ...condition })),
    guidance: changes.guidance ?? [...template.guidance],
    recommendedChannels: changes.recommendedChannels ?? [...template.recommendedChannels],
  };
}
