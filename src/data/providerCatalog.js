export function weatherProviderById(providerId) {
  return WEATHER_PROVIDER_CATALOG.find((provider) => provider.id === providerId) ?? null;
}

export function weatherProvidersForCapability(capability, options = {}) {
  return WEATHER_PROVIDER_CATALOG.filter((provider) => (
    provider.capabilities.includes(capability)
    && (!options.region || provider.geographicCoverage.includes('global') || provider.geographicCoverage.includes(options.region))
    && (options.historical === undefined || provider.supportsHistorical === options.historical)
    && (options.bulk === undefined || provider.supportsBulk === options.bulk)
  ));
}

export function weatherProviderCapabilities() {
  return [...new Set(WEATHER_PROVIDER_CATALOG.flatMap((provider) => provider.capabilities))].sort();
}

export function weatherProviderAttributions(providerIds) {
  return [...new Set(providerIds.map(weatherProviderById).filter(Boolean).map((provider) => provider.attribution))];
}
